import java.sql.*;
import java.util.Scanner;

public class AppointmentScheduler {
    static final String URL="jdbc:oracle:thin:@localhost:1521/XEPDB1";
    static final String USER="system";
    static final String PASS="your_password";
    static Scanner sc=new Scanner(System.in);

    static Connection con() throws SQLException {
        return DriverManager.getConnection(URL,USER,PASS);
    }

    static void setup() throws SQLException {
        try(Connection c=con();Statement s=c.createStatement()) {
            try {
                s.executeUpdate("CREATE TABLE providers(id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name VARCHAR2(50))");
            } catch(SQLException e) {
                if(e.getErrorCode()!=955) throw e;
            }
            try {
                s.executeUpdate("CREATE TABLE slots(id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,provider_id NUMBER REFERENCES providers(id),slot_time TIMESTAMP,patient VARCHAR2(50),UNIQUE(slot_time,provider_id))");
            } catch(SQLException e) {
                if(e.getErrorCode()!=955) throw e;
            }
        }
    }

    static void addProvider() throws SQLException {
        System.out.print("Provider name: ");
        String name=sc.nextLine();
        try(Connection c=con();PreparedStatement p=c.prepareStatement(
            "INSERT INTO providers(name) VALUES(?)")) {
            p.setString(1,name);
            p.executeUpdate();
            System.out.println("Provider added.");
        }
    }

    static void addSlot() throws SQLException {
        System.out.print("Provider ID: ");
        int id=Integer.parseInt(sc.nextLine());
        System.out.print("Slot time (YYYY-MM-DD HH24:MI): ");
        String time=sc.nextLine();
        try(Connection c=con();PreparedStatement p=c.prepareStatement(
            "INSERT INTO slots(provider_id,slot_time) VALUES(?,TO_TIMESTAMP(?,'YYYY-MM-DD HH24:MI'))")) {
            p.setInt(1,id);
            p.setString(2,time);
            p.executeUpdate();
            System.out.println("Slot added.");
        }
    }

    static void viewSlots() throws SQLException {
        try(Connection c=con();Statement s=c.createStatement();
            ResultSet r=s.executeQuery(
                "SELECT s.id,p.name,s.slot_time,s.patient FROM slots s JOIN providers p ON p.id=s.provider_id ORDER BY s.slot_time")) {
            while(r.next())
                System.out.println("Slot "+r.getInt(1)+" | "+r.getString(2)+" | "+r.getTimestamp(3)+" | "+(r.getString(4)==null?"Available":r.getString(4)));
        }
    }

    static void book() throws SQLException {
        System.out.print("Slot ID: ");
        int id=Integer.parseInt(sc.nextLine());
        System.out.print("Your name: ");
        String name=sc.nextLine();
        try(Connection c=con();PreparedStatement p=c.prepareStatement(
            "UPDATE slots SET patient=? WHERE id=? AND patient IS NULL")) {
            p.setString(1,name);
            p.setInt(2,id);
            if(p.executeUpdate()==1)
                System.out.println("Appointment booked.");
            else
                System.out.println("Slot not found or already booked.");
        }
    }

    static void cancel() throws SQLException {
        System.out.print("Slot ID: ");
        int id=Integer.parseInt(sc.nextLine());
        try(Connection c=con();PreparedStatement p=c.prepareStatement(
            "UPDATE slots SET patient=NULL WHERE id=? AND patient IS NOT NULL")) {
            p.setInt(1,id);
            System.out.println(p.executeUpdate()==1?"Appointment cancelled.":"No booking found.");
        }
    }

    public static void main(String[] args) {
        try {
            Class.forName("oracle.jdbc.OracleDriver");
            setup();
            while(true) {
                System.out.println("\n1.Add Provider  2.Add Slot  3.View Slots  4.Book  5.Cancel  0.Exit");
                System.out.print("Choice: ");
                int ch=Integer.parseInt(sc.nextLine());
                switch(ch) {
                    case 1: addProvider(); break;
                    case 2: addSlot(); break;
                    case 3: viewSlots(); break;
                    case 4: book(); break;
                    case 5: cancel(); break;
                    case 0: return;
                    default: System.out.println("Invalid choice.");
                }
            }
        } catch(Exception e) {
            System.out.println("Error: "+e.getMessage());
        }
    }
}